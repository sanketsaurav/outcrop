export function generatePasscode(): string {
	const r = new Uint32Array(3);
	crypto.getRandomValues(r);
	const adj = ADJECTIVES[r[0] % ADJECTIVES.length];
	const noun = NOUNS[r[1] % NOUNS.length];
	const num = 10 + (r[2] % 90);
	return `${adj}-${noun}-${num}`;
}
